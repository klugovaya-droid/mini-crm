import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

function parseEnv(output: string): Record<string, string> {
  const values: Record<string, string> = {};
  for (const line of output.split("\n")) {
    const match = line.match(/^([A-Z0-9_]+)=(?:"(.*)"|(.*))$/);
    if (match) values[match[1]] = match[2] ?? match[3] ?? "";
  }
  return values;
}

const output = execFileSync("npx", ["supabase", "status", "-o", "env"], {
  encoding: "utf8",
});
const values = parseEnv(output);
const url = values.API_URL ?? values.SUPABASE_URL;
const anonKey = values.ANON_KEY ?? values.SUPABASE_ANON_KEY;
const serviceRoleKey = values.SERVICE_ROLE_KEY ?? values.SUPABASE_SERVICE_ROLE_KEY;

if (!url || !anonKey || !serviceRoleKey) {
  throw new Error("Could not read local Supabase credentials from `supabase status`.");
}

const password = process.env.DEMO_PASSWORD ?? "Demo1234!";
const content = [
  "# Generated by `npm run env:local`. Do not commit.",
  `VITE_SUPABASE_URL=${url}`,
  `VITE_SUPABASE_ANON_KEY=${anonKey}`,
  `SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey}`,
  `DEMO_PASSWORD=${password}`,
  "",
].join("\n");

writeFileSync(".env.local", content);
console.log("Wrote .env.local with local Supabase credentials.");
