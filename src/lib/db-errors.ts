export function mapDbError(error: PostgrestError | null | undefined): string {
  if (!error) return "Не удалось выполнить действие.";

  const byCode = codeMessages[error.code];
  if (byCode) return byCode;

  const byMessage = messageHints.find(([hint]) => error.message.includes(hint));
  if (byMessage) return byMessage[1];

  return "Не удалось выполнить действие. Попробуйте ещё раз.";
}
